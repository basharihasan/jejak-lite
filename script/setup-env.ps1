# Generate .env for Docker/Podman self-host — no Ruby/Rails required.
# Windows PowerShell 5.1+ / PowerShell 7+ (uses .NET RNG; OpenSSL not required).
param(
  [switch]$Force,
  [string]$HostAddress = "",
  [int]$Port = 3000
)

$ErrorActionPreference = "Stop"

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$Root = Split-Path -Parent $ScriptDir
$EnvFile = Join-Path $Root ".env"
$Example = Join-Path $Root ".env.example"

if (-not (Test-Path $Example)) {
  throw "Missing .env.example at $Example"
}

if ((Test-Path $EnvFile) -and -not $Force) {
  throw ".env already exists. Re-run with -Force to overwrite (old encryption keys will be lost)."
}

function New-HexBytes([int]$ByteCount) {
  $bytes = New-Object byte[] $ByteCount
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  try {
    $rng.GetBytes($bytes)
  } finally {
    $rng.Dispose()
  }
  return ([System.BitConverter]::ToString($bytes) -replace "-", "").ToLowerInvariant()
}

if ([string]::IsNullOrWhiteSpace($HostAddress)) {
  $HostAddress = "192.168.1.50:$Port"
}

$pg = New-HexBytes 24
$sk = New-HexBytes 64
$k1 = New-HexBytes 16
$k2 = New-HexBytes 16
$k3 = New-HexBytes 16

$lines = @(
  "# Generated by script/setup-env.ps1 — do not commit."
  "POSTGRES_PASSWORD=$pg"
  "SECRET_KEY_BASE=$sk"
  "AR_ENCRYPTION_PRIMARY_KEY=$k1"
  "AR_ENCRYPTION_DETERMINISTIC_KEY=$k2"
  "AR_ENCRYPTION_KEY_DERIVATION_SALT=$k3"
  "APP_HOST=$HostAddress"
  "HOST_PORT=$Port"
  "ASSUME_SSL=false"
  "FORCE_SSL=false"
  "R2_ACCOUNT_ID="
  "R2_ACCESS_KEY_ID="
  "R2_SECRET_ACCESS_KEY="
  "R2_BUCKET="
)

$utf8 = New-Object System.Text.UTF8Encoding $false
[System.IO.File]::WriteAllLines($EnvFile, $lines, $utf8)

Write-Host "Wrote $EnvFile"
Write-Host "Edit APP_HOST if needed, then:"
Write-Host "  docker compose pull"
Write-Host "  docker compose up -d"
Write-Host "  docker compose exec web bin/rails demo:seed"
