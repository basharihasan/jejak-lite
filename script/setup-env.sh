#!/usr/bin/env bash
# Generate .env for Docker/Podman self-host — no Ruby/Rails required.
# Linux (Debian/Ubuntu/Fedora/RHEL/Arch/…) and macOS with openssl or LibreSSL.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
ENV_FILE="$ROOT/.env"
EXAMPLE="$ROOT/.env.example"
FORCE=0

usage() {
  echo "Usage: $0 [--force] [--host APP_HOST] [--port HOST_PORT]"
  echo "  Creates .env with random secrets (openssl). No Ruby needed."
  exit "${1:-0}"
}

APP_HOST_ARG=""
HOST_PORT_ARG="3000"

while [[ $# -gt 0 ]]; do
  case "$1" in
    -h|--help) usage 0 ;;
    --force) FORCE=1; shift ;;
    --host) APP_HOST_ARG="${2:?}"; shift 2 ;;
    --port) HOST_PORT_ARG="${2:?}"; shift 2 ;;
    *) echo "Unknown option: $1" >&2; usage 1 ;;
  esac
done

if [[ ! -f "$EXAMPLE" ]]; then
  echo "Missing .env.example at $EXAMPLE" >&2
  exit 1
fi

if [[ -f "$ENV_FILE" && "$FORCE" -ne 1 ]]; then
  echo ".env already exists. Re-run with --force to overwrite (old encryption keys will be lost)." >&2
  exit 1
fi

if ! command -v openssl >/dev/null 2>&1; then
  echo "openssl not found. Install it first, e.g.:" >&2
  echo "  Debian/Ubuntu: sudo apt install openssl" >&2
  echo "  Fedora/RHEL:   sudo dnf install openssl" >&2
  echo "  Arch:          sudo pacman -S openssl" >&2
  echo "  macOS:         (usually preinstalled) or brew install openssl" >&2
  exit 1
fi

hex() { openssl rand -hex "$1"; }

if [[ -z "$APP_HOST_ARG" ]]; then
  # Best-effort LAN hint; user should edit APP_HOST if wrong.
  if command -v hostname >/dev/null 2>&1; then
    ip="$(hostname -I 2>/dev/null | awk '{print $1}' || true)"
  fi
  APP_HOST_ARG="${ip:-192.168.1.50}:${HOST_PORT_ARG}"
fi

cat > "$ENV_FILE" <<EOF
# Generated by script/setup-env.sh — do not commit.
POSTGRES_PASSWORD=$(hex 24)
SECRET_KEY_BASE=$(hex 64)
AR_ENCRYPTION_PRIMARY_KEY=$(hex 16)
AR_ENCRYPTION_DETERMINISTIC_KEY=$(hex 16)
AR_ENCRYPTION_KEY_DERIVATION_SALT=$(hex 16)
APP_HOST=${APP_HOST_ARG}
HOST_PORT=${HOST_PORT_ARG}
ASSUME_SSL=false
FORCE_SSL=false
R2_ACCOUNT_ID=
R2_ACCESS_KEY_ID=
R2_SECRET_ACCESS_KEY=
R2_BUCKET=
EOF

chmod 600 "$ENV_FILE" 2>/dev/null || true

echo "Wrote $ENV_FILE"
echo "Edit APP_HOST if needed, then:"
echo "  docker compose pull && docker compose up -d"
echo "  docker compose exec web bin/rails demo:seed"
